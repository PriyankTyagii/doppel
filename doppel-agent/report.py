"""Markdown parity report."""

from __future__ import annotations

from typing import Any


def _rs(x: float) -> str:
    return f"₹{x:,.2f}"


def render_markdown(run: dict[str, Any]) -> str:
    s = run["summary"]
    imp = s.get("impact") or {}
    prev = run.get("previous_summary")
    lines = [
        "# Doppel parity report",
        "",
        f"**{s['headline']}**",
        "",
        f"- Run `{run['run_id']}` at {run['started_at']} ({run['duration_s']}s), billing-v2 at `{run.get('v2_commit', '')[:8]}`",
        f"- Parity: **{s['identical']}/{s['total']} scenarios identical ({s['parity_pct']}%)**"
        + (f", previous run {prev['parity_pct']}%" if prev else ""),
        f"- Status vs previous run: " + ", ".join(f"{k} {v}" for k, v in run["counts"].items()),
    ]
    if imp:
        lines += [
            f"- Sample impact: {imp['invoices_affected']} invoices wrong, {_rs(imp['rupees_wrong'])} mis-billed "
            f"({imp['overcharged']} overcharged, {imp['undercharged']} undercharged), "
            f"{_rs(imp['tax_misreported'])} GST misreported",
            f"- {s['projection_note']} Projected monthly: {_rs(imp['projected_monthly_rupees'])} mis-billed, "
            f"{_rs(imp['projected_monthly_tax'])} GST misreported. *This is a projection from the sample, not a measurement.*",
        ]
    lines += ["", "## Mismatch groups", ""]
    if not run["groups"]:
        lines.append("None. billing-v2 matched billing-v1 on every scenario.")
    for g in run["groups"]:
        e = g.get("explanation") or {}
        gi = g.get("impact") or {}
        lines += [
            f"### [{g['status']}] {e.get('cause') or ', '.join(g['fields'])}",
            "",
            f"- Scenarios: {', '.join(g['scenario_ids'])} ({gi.get('invoices_affected', len(g['scenario_ids']))} invoices)",
            f"- Fields: {', '.join(g['fields'])}",
        ]
        if gi:
            lines.append(f"- Impact: {_rs(gi['rupees_wrong'])} mis-billed ({gi['overcharged']} over, {gi['undercharged']} under), "
                         f"{_rs(gi['tax_misreported'])} GST misreported; projected {_rs(gi['projected_monthly_rupees'])}/month")
        if e:
            lines += [
                f"- Root cause: {e.get('explanation', '')}",
                f"- Code: v1 `{e.get('v1_file')}:{e.get('v1_line')}` vs v2 `{e.get('v2_file')}:{e.get('v2_line')}`",
            ]
            if e.get("recent_change") and e.get("changed_line"):
                lines.append(f"- Changed since last run: `{e['changed_line']}`")
            if e.get("suggested_fix"):
                lines.append(f"- Suggested fix (for a human to apply): {e['suggested_fix']}")
        lines.append("")
    lines += ["## All scenarios", "", "| Scenario | Kind | Result | Status | Bill Δ | GST Δ |", "|---|---|---|---|---|---|"]
    for r in run["results"]:
        i = r["impact"]
        lines.append(f"| {r['id']} {r['summary']} | {r['kind']} | {'identical' if r['match'] else 'differs'} | "
                     f"{r['status']} | {i['bill_delta']:+.2f} | {i['tax_delta']:+.2f} |")
    lines += ["", "_Generated by Doppel. The agent is read-only: it never edits either codebase._"]
    return "\n".join(lines)
